import {env} from './lib.mjs';
import {spawnSync} from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
const dir='/private/tmp/claude-501/-Users-user-Projects-Web3-Hackathon-Valtrum-on-NEAR-Code/194d9507-2b0a-4ff0-b7ee-f08c6f0448f7/scratchpad/ks';
fs.mkdirSync(dir,{recursive:true,mode:0o700});
const pw='ephemeral-'+crypto.randomBytes(8).toString('hex');
fs.writeFileSync(dir+'/pw',pw,{mode:0o600});
const key=Buffer.from(env.TESTNET_EVM_DEPLOYER_PRIVATE_KEY.replace(/^0x/,''),'hex');
if(key.length!==32)throw new Error('bad key length');
const salt=crypto.randomBytes(32),iv=crypto.randomBytes(16);
const dk=crypto.scryptSync(pw,salt,32,{N:8192,r:8,p:1});
const c=crypto.createCipheriv('aes-128-ctr',dk.subarray(0,16),iv);
const ct=Buffer.concat([c.update(key),c.final()]);
const macIn=Buffer.concat([dk.subarray(16,32),ct]).toString('hex');
const mac=spawnSync('cast',['keccak','0x'+macIn],{encoding:'utf8'}).stdout.trim().replace(/^0x/,'');
const ks={version:3,id:crypto.randomUUID(),address:env.TESTNET_EVM_DEPLOYER_ADDRESS.replace(/^0x/,'').toLowerCase(),crypto:{ciphertext:ct.toString('hex'),cipherparams:{iv:iv.toString('hex')},cipher:'aes-128-ctr',kdf:'scrypt',kdfparams:{dklen:32,salt:salt.toString('hex'),n:8192,r:8,p:1},mac}};
fs.writeFileSync(dir+'/deployer',JSON.stringify(ks),{mode:0o600});
console.log('ok');
